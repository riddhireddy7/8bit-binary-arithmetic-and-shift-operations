# Logical left shift
num = "10110110"

print("(a) Left shift")
print("Original number:", num)

for i in range(2):
    num = num[1:] + "0"
    print("After shift", i + 1, ":", num)

print("Final result:", num)
print("Decimal value:", int(num, 2))


# Logical right shift
num = "11010100"

print("\n(b) Right shift")
print("Original number:", num)

for i in range(2):
    num = "0" + num[:-1]
    print("After shift", i + 1, ":", num)

print("Final result:", num)
print("Decimal value:", int(num, 2))