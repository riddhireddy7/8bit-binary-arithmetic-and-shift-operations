def binary(n):
    return format(n & 255, '08b')

def calculate(a, b):
    x = binary(a)
    y = binary(b)
    result = (int(x, 2) + int(y, 2)) & 255
    ans = result if result < 128 else result - 256

    print("First number :", x, "=", a)
    print("Second number:", y, "=", b)
    print("Binary result:", binary(result))
    print("Decimal result:", ans)

    if (a >= 0) == (b >= 0) and (ans >= 0) != (a >= 0):
        print("Overflow: Yes")
    else:
        print("Overflow: No")

    print("Expected result:", a + b)
    print()

print("(a) 25 + (+18)")
calculate(25, 18)

print("(b) (-25) + (-18)")
calculate(-25, -18)